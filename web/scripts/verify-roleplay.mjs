// Runs a whole DECA role-play with a fake camera and microphone, then checks the recording and the rubric. Usage: node scripts/verify-roleplay.mjs [baseUrl]
import { chromium } from "playwright-core";
const base = process.argv[2] ?? "http://127.0.0.1:3400";
const b = await chromium.launch({ channel: "chrome", args: ["--use-fake-device-for-media-stream", "--use-fake-ui-for-media-stream"] });
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, permissions: ["camera", "microphone"] });
const p = await ctx.newPage();
const errs = [];
p.on("pageerror", (e) => errs.push(e.message));
await p.goto(`${base}/deca/roleplay`, { waitUntil: "networkidle" });
await p.getByRole("button", { name: /Marketing/ }).first().click();
await p.waitForTimeout(600);
await p.screenshot({ path: "scripts/rp-clusters.png" });
await p.getByRole("link", { name: /MCS/ }).first().click();
await p.waitForURL("**/deca/events/mcs/**", { timeout: 10000 }).catch(() => {});
await p.waitForTimeout(1200);
await p.screenshot({ path: "scripts/rp-event.png" });
await p.locator("ol button").first().click();
await p.getByRole("button", { name: /Turn on camera/ }).click();
await p.waitForTimeout(1500);
await p.screenshot({ path: "scripts/rp-setup.png" });
await p.getByRole("button", { name: /Start prep/ }).click();
await p.waitForTimeout(800);
await p.locator("textarea").fill("Open with the buzz idea. Cover each indicator. Close with how I would measure results.");
await p.screenshot({ path: "scripts/rp-prep.png" });
await p.getByRole("button", { name: /ready, start presenting/ }).click();
await p.waitForTimeout(3500);
const hasPrompt = await p.getByText("Performance indicators").count();
console.log("prompt hidden while presenting:", hasPrompt === 0);
await p.screenshot({ path: "scripts/rp-present.png" });
await p.getByRole("button", { name: /done presenting/ }).click();
await p.waitForTimeout(800);
await p.screenshot({ path: "scripts/rp-ask.png" });
await p.getByRole("button", { name: /Finish and review/ }).click();
await p.waitForURL((u) => u.pathname.includes("/deca/recordings") && u.search.includes("id="), { timeout: 15000 });
await p.waitForTimeout(1500);
console.log("review url:", p.url());
const video = await p.locator("video").count();
const dur = await p.evaluate(() => { const v = document.querySelector("video"); return v ? { size: v.currentSrc ? 1 : 0, ready: v.readyState } : null; });
console.log("video element:", video, dur);
// score a few rows
const sliders = p.locator('input[type="range"]');
const n = await sliders.count();
for (let i = 0; i < n; i++) await sliders.nth(i).fill(String(Math.min(6, 3 + (i % 3))));
await p.waitForTimeout(900);
console.log("rubric rows:", n, "| total:", (await p.locator("strong").last().innerText()));
await p.screenshot({ path: "scripts/rp-review.png", fullPage: true });
console.log("errors:", errs);
await b.close();
