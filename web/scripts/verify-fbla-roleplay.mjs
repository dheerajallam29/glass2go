// Runs a whole FBLA role play with a fake camera and microphone: pick an event, prep, present (judge cue), review and score.
// Usage: node scripts/verify-fbla-roleplay.mjs [baseUrl]
import { chromium } from "playwright-core";
const base = process.argv[2] ?? "http://localhost:3000";
const b = await chromium.launch({ channel: "chrome", args: ["--use-fake-device-for-media-stream", "--use-fake-ui-for-media-stream"] });
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, permissions: ["camera", "microphone"] });
const p = await ctx.newPage();
const errs = [];
p.on("pageerror", (e) => errs.push(e.message));
await p.goto(`${base}/fbla/roleplay`, { waitUntil: "networkidle" });
await p.getByRole("button", { name: /Management \+ Entrepreneurship/ }).first().click();
await p.waitForTimeout(600);
await p.screenshot({ path: "scripts/fb-clusters.png" });
await p.getByRole("link", { name: /Business Management/ }).first().click();
await p.waitForURL("**/fbla/events/business-management**", { timeout: 15000 });
await p.waitForTimeout(1200);
await p.screenshot({ path: "scripts/fb-event.png", fullPage: true });
await p.locator("ol button").first().click();
await p.getByRole("button", { name: /Turn on camera/ }).click();
await p.waitForTimeout(1500);
await p.getByRole("button", { name: /Start prep/ }).click();
await p.waitForTimeout(800);
await p.locator("textarea").fill("Problem: turnover. Options: raise pay, lead role, scheduling. Plan within 5 percent.");
await p.screenshot({ path: "scripts/fb-prep.png", fullPage: true });
console.log("prep shows knowledge areas:", (await p.getByText("Knowledge areas this case lets you show").count()) === 1);
await p.getByRole("button", { name: /ready, start presenting/ }).click();
await p.waitForTimeout(2500);
console.log("case hidden while presenting:", (await p.getByText("Role play case").count()) === 0);
await p.getByRole("button", { name: /Judge steps in/ }).click();
await p.waitForTimeout(500);
console.log("judge cue shown:", (await p.getByText(/\(judge\) says/).count()) === 1);
await p.screenshot({ path: "scripts/fb-present.png" });
await p.getByRole("button", { name: /finish and review/ }).click();
await p.waitForURL((u) => u.pathname.includes("/fbla/recordings") && u.search.includes("id="), { timeout: 90000 });
await p.waitForTimeout(1500);
console.log("review url:", p.url());
const sliders = p.locator('input[type="range"]');
const n = await sliders.count();
for (let i = 0; i < n; i++) await sliders.nth(i).fill("8");
await p.waitForTimeout(900);
console.log("rubric rows:", n, "| total:", await p.locator("strong").last().innerText());
await p.screenshot({ path: "scripts/fb-review.png", fullPage: true });
await p.goto(`${base}/fbla/recordings`, { waitUntil: "networkidle" });
console.log("list shows it:", (await p.getByText("Business Management").count()) > 0);
console.log("errors:", errs);
await b.close();
